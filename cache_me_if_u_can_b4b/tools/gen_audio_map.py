"""Write src/audio/audioMap.ts from the mp3 files in assets/audio. Run after tools/gen_audio.py."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AUDIO_DIR = ROOT / "assets" / "audio"
OUT = ROOT / "src" / "audio" / "audioMap.ts"


def main():
    ids = sorted(p.stem for p in AUDIO_DIR.glob("*.mp3")) if AUDIO_DIR.exists() else []
    lines = ["// generated by tools/gen_audio_map.py. Do not edit.",
             "export const AUDIO: Record<string, number> = {"]
    lines += [f'  "{i}": require("../../assets/audio/{i}.mp3"),' for i in ids]
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(ids)} clips in {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
